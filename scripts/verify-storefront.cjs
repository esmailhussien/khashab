const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const base = process.env.SITE_URL || 'http://127.0.0.1:5175';
const output = path.join(process.cwd(), '.review');
fs.mkdirSync(output, { recursive: true });
(async () => {
  const browser = await chromium.launch({ channel: process.env.BROWSER_CHANNEL || 'msedge', headless: true });
  const failures = [];
  const checks = [];
  try {
    const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    const page = await context.newPage();
    page.on('pageerror', error => failures.push(error.message));
    const go = async route => { await page.goto(base + route, { waitUntil: 'networkidle' }); await page.locator('main .page-container').waitFor(); };
    const count = async expected => { await page.waitForFunction(n => document.querySelectorAll('#store-products-grid .product-card').length === n, expected); };
    const capture = async name => { await page.screenshot({ path: path.join(output, name + '.png'), fullPage: true }); };
    await go('/');
    assert.equal(await page.locator('.signature-grid .product-card').count(), 4);
    await capture('home-desktop');
    const homeLinks = await page.locator('main a').evaluateAll(links => links.map(a => a.getAttribute('href')));
    assert(homeLinks.every(href => href && !href.startsWith('#/')));
    checks.push('Homepage displays four real products and valid destination links');
    await page.locator('.signature-grid .product-card-wishlist').first().click();
    await page.locator('a[aria-label="Wishlist"]').click();
    await page.locator('#wishlist-products-grid .product-card').waitFor();
    await page.locator('#wishlist-products-grid .product-card-wishlist').click();
    await page.locator('.wishlist-empty-state').waitFor();
    checks.push('Wishlist add, navigation and removal');
    await go('/store');
    await count(4);
    await page.locator('.filter-price[value="under-1000"]').check();
    await count(1);
    assert.match(await page.locator('#store-products-grid').innerText(), /900/);
    await page.locator('#clear-store-filters').click();
    await count(4);
    await page.locator('.filter-wood[value="Walnut"]').check();
    await count(1);
    await page.locator('.category-pill[data-cat="plates"]').click();
    assert.match(page.url(), /wood=Walnut/);
    await page.reload({ waitUntil: 'networkidle' });
    await count(1);
    assert(await page.locator('.filter-wood[value="Walnut"]').isChecked());
    await page.locator('#clear-store-filters').click();
    await count(4);
    await page.goBack({ waitUntil: 'networkidle' });
    await count(1);
    checks.push('EGP price filtering, wood filtering, URL persistence, reload and back');
    await go('/store?wood=Oak');
    await count(1);
    await page.locator('#clear-store-filters').click();
    await page.locator('#store-sort').selectOption('price-high');
    const values = await page.locator('#store-products-grid .product-card-price').allTextContents();
    assert(values[0].includes('1,500'));
    await page.locator('#store-search').fill('no-such-product');
    await page.locator('#store-search-form button').click();
    await page.locator('#store-empty-state').waitFor();
    await page.locator('#btn-reset-filters').click();
    await count(4);
    assert.equal(await page.locator('#store-search').inputValue(), '');
    await go('/store?search=' + encodeURIComponent('<img src=x onerror="window.__unsafe=1">'));
    await page.locator('#store-empty-state').waitFor();
    assert.equal(await page.evaluate(() => window.__unsafe), undefined);
    assert.equal(await page.locator('main img[src="x"]').count(), 0);
    checks.push('Price ordering, empty state reset and safe search text');
    await go('/store');
    await capture('store-desktop');
    await page.locator('[data-id="3d-wooden-plate"] .card-action').click();
    await page.locator('#btn-add-to-cart').waitFor();
    await page.locator('.wood-option[data-wood="Sapele"]').press('Enter');
    assert.match(await page.locator('.product-detail-price').innerText(), /1,300/);
    assert.equal(await page.locator('#product-selected-material').innerText(), 'Sapele');
    await page.locator('.size-option').nth(1).click();
    assert.match(await page.locator('#product-size-dimensions').innerText(), /50 cm/);
    const secondView = page.locator('.gallery-figure').nth(1);
    assert.match(await secondView.locator('img').getAttribute('src'), /sapele 2/);
    await secondView.press('Enter');
    await page.locator('.lightbox-modal.active').waitFor();
    assert.match(await page.locator('#lightbox-image').getAttribute('src'), /sapele 2/);
    await page.keyboard.press('Escape');
    await capture('product-desktop');
    await page.locator('#btn-add-to-cart').click();
    await page.locator('#cart-panel.active').waitFor();
    const item = await page.evaluate(() => JSON.parse(localStorage.getItem('khashab_cart'))[0]);
    assert.equal(item.price, 1300);
    assert.equal(item.woodType, 'Sapele');
    assert.match(item.size, /X-Large/);
    await page.locator('#btn-cart-checkout').click();
    await page.locator('#form-shipping').waitFor();
    assert.match(await page.locator('.order-summary-box').innerText(), /1,300/);
    checks.push('Keyboard variant and gallery selection, matching cart price, size and checkout');
    for (const route of ['/discover?tab=wiki', '/discover?tab=care', '/our-story', '/configurator', '/contact', '/return-policy']) {
      await go(route);
      assert((await page.locator('main').innerText()).trim().length > 100);
    }
    checks.push('Existing story, wood library, care, customisation, contact and returns routes load');
    for (const width of [390, 768, 1024]) {
      await page.setViewportSize({ width, height: 900 });
      for (const route of ['/', '/store', '/product/3d-wooden-plate']) {
        await go(route);
        const overflow = await page.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth }));
        assert(overflow.scroll <= width, `${route} overflows at ${width}: ${overflow.scroll}`);
        if (width === 390) await capture(route === '/' ? 'home-mobile' : route === '/store' ? 'store-mobile' : 'product-mobile');
      }
    }
    await page.setViewportSize({ width: 390, height: 844 });
    await go('/');
    await page.locator('#btn-mobile-toggle').click();
    assert.equal(await page.locator('#btn-mobile-toggle').getAttribute('aria-expanded'), 'true');
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#btn-mobile-toggle').getAttribute('aria-expanded'), 'false');
    await page.locator('#btn-mobile-toggle').click();
    await page.locator('#mobile-drawer a[href="/store"]').click();
    await count(4);
    assert.equal(await page.locator('#btn-mobile-toggle').getAttribute('aria-expanded'), 'false');
    await page.locator('#btn-mobile-filter').click();
    await page.locator('.filter-price[value="under-1000"]').check();
    await count(1);
    await page.locator('#btn-search-toggle').click();
    await page.locator('#nav-search-input').fill('beech');
    await page.locator('#nav-search-input').press('Enter');
    await page.waitForFunction(() => document.querySelector('#store-products-grid')?.textContent.includes('Beech'));
    await count(1);
    assert.match(await page.locator('#store-products-grid').innerText(), /Beech/);
    checks.push('390/768/1024 responsive layouts, mobile menu, Escape, mobile filters and search');
    assert.deepEqual(failures, [], 'No browser runtime errors');
    fs.writeFileSync(path.join(output, 'verification.json'), JSON.stringify({ passed: checks, pageErrors: failures }, null, 2));
    console.log(JSON.stringify({ passed: checks, pageErrors: failures }, null, 2));
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
